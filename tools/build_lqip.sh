#!/usr/bin/env bash
# Generates assets/js/lqip.js — tiny base64 WebP placeholders used for the blur-up effect.
# Requires ImageMagick. Run from repo root:  bash tools/build_lqip.sh
set -e
out=assets/js/lqip.js
echo "/* Auto-generated by tools/build_lqip.sh — do not edit by hand. */" > $out
echo "window.IA_LQIP = {" >> $out
for f in assets/img/*.webp; do
  b=$(basename "$f" .webp)
  case "$b" in *-800|*-480|og-*|icon-*) continue;; esac
  d=$(convert "$f" -resize 20x -strip -quality 40 webp:- | base64 -w0)
  echo "  \"$b\": \"data:image/webp;base64,$d\"," >> $out
done
echo "};" >> $out
echo "wrote $out ($(wc -c < $out) bytes)"
